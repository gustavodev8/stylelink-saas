// Inicializar
async function init() {
  if (!slug) {
    showError('Nenhuma loja especificada. Por favor, acesse um link válido.');
    return;
  }

  try {
    // Buscar dados da loja
    const storeData = await fetchStoreData(slug);

    // Renderizar página
    renderStore(storeData);

    // Esconder loading e mostrar conteúdo
    loadingScreen.style.display = 'none';
    mainContainer.style.display = 'block';
  } catch (error) {
    console.error('Erro ao carregar loja:', error);
    showError(error.message || 'Não foi possível carregar a loja. Tente novamente mais tarde.');
  }
}

// Buscar dados da loja
async function fetchStoreData(slug) {
  const response = await fetch(`${API_URL}/public/store/${slug}`);

  if (!response.ok) {
    if (response.status === 404) {
      throw new Error('Loja não encontrada. Verifique se o link está correto.');
    }
    throw new Error('Erro ao carregar loja');
  }

  return await response.json();
}

// Renderizar loja
function renderStore(data) {
  const { store, products, socialLinks: socials } = data;

  // Título da página
  pageTitle.textContent = `${store.name || 'Loja'} - StyleLink`;

  // Avatar
  if (store.avatar) {
    storeAvatar.src = store.avatar;
  }

  // Nome da loja
  storeName.textContent = store.name || 'Minha Loja';

  // Descrição
  storeDescription.textContent = store.bio || store.description || 'Bem-vindo ao meu link in bio!';

  // Redes sociais
  if (socials && socials.length > 0) {
    renderSocialLinks(socials);
  } else {
    socialLinks.style.display = 'none';
  }

  // Produtos
  if (products && products.length > 0) {
    renderProducts(products);
  } else {
    productsSection.innerHTML = `
      <div class="empty-state">
        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
          <path d="M20.59 13.41l-7.17 7.17a2 2 0 01-2.83 0L2 12V2h10l8.59 8.59a2 2 0 010 2.82z"/>
          <line x1="7" y1="7" x2="7.01" y2="7"/>
        </svg>
        <h3>Nenhum produto disponível</h3>
        <p>Em breve teremos novidades!</p>
      </div>
    `;
  }
}

// Renderizar redes sociais
function renderSocialLinks(socials) {
  socialLinks.innerHTML = socials
    .filter(s => s.is_active || s.isActive)
    .map(social => {
      const platform = social.platform.toLowerCase();
      const icon = socialIcons[platform] || '';

      return `
        <a href="${social.url}" target="_blank" rel="noopener noreferrer"
           class="social-btn ${platform}" title="${social.platform}">
          ${icon}
        </a>
      `;
    })
    .join('');
}

// Renderizar produtos
